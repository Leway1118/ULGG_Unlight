import json,pathlib,sys,shutil
from playwright.sync_api import sync_playwright,expect
src=pathlib.Path(sys.argv[1]).resolve();out=pathlib.Path(sys.argv[2]);out.mkdir(parents=True,exist_ok=True)
reports=[]
with sync_playwright() as p:
    exe=next((shutil.which(x) for x in ['chromium','google-chrome','google-chrome-stable'] if shutil.which(x)),None)
    assert exe,'system Chromium required'
    b=p.chromium.launch(executable_path=exe,headless=True,args=['--no-sandbox','--disable-background-networking'])
    for width,height in [(360,740),(1280,850)]:
        ctx=b.new_context(viewport={'width':width,'height':height},reduced_motion='reduce',accept_downloads=True,has_touch=width==360,is_mobile=width==360)
        page=ctx.new_page();cases=[];errors=[];network=[]
        page.on('pageerror',lambda e:errors.append(str(e)));page.on('request',lambda r:network.append(r.url) if r.url.startswith(('http:','https:')) else None)
        page.route('http**/*',lambda r:r.abort())
        def ck(x,n):
            assert x,n
            cases.append(n)
        def step(i):
            page.locator('#progress button').nth(i).click()
            expect(page.locator('#slide-'+str(i))).to_be_visible()
            ck(page.evaluate('document.documentElement.scrollWidth<=innerWidth'),'overflow_'+str(i))
        def scenario(name):
            page.locator('#scenario').select_option(name)
            expect(page.locator('#slide-0')).to_be_visible()
        def text(id):return page.locator('#'+id).inner_text()
        def scope(i):return page.locator('#slide-'+str(i)).get_attribute('data-scope')
        page.set_content(src.read_text(),wait_until='load')
        ck(page.locator('.slide').count()==11,'eleven_chapters')
        ck(scope(1)=='PERSONAL' and scope(7)=='PUBLIC' and scope(9)=='PERSONAL','private_first')
        step(1);ck(text('matches')=='174' and text('rate')=='56.3%','legacy_battle')
        step(2);page.locator('#guess-options button[data-id="22"]').click();page.locator('#reveal').click();expect(page.locator('#guess-feedback')).to_have_text('猜對了！')
        step(3);page.locator('#team-best').click();ck('76.4%' in text('team-matches'),'legacy_team')
        step(4);page.locator('#months button').nth(6).click();ck('24' in text('month-title'),'legacy_month')
        step(5);ck(text('concentration')=='43.1%' and text('hero-rate')=='74.7%','legacy_highlights')
        step(6)
        for _ in range(3):page.locator('#quiz button').nth(1).click()
        expect(page.locator('#persona-name')).to_have_text('破陣先鋒')
        step(9);ck(text('fortune-count')=='33' and text('fortune-streak')=='3','annual_rows_and_streak')
        ck(text('fortune-five')=='6','stars')
        ck(text('fortune-exp')=='1892' and text('fortune-level')=='19' and text('fortune-all-draws')=='112','lifetime_separate')
        ck(page.locator('#fortune-radar polygon').count()==5 and page.locator('#fortune-values span').count()==6,'radar_six_axes')
        ck(page.locator('#fortune-months button').nth(11).is_disabled(),'future_month')
        page.locator('#fortune-months button').nth(0).click();ck(text('fortune-month-count')=='3','monthly_click')
        page.locator('#fortune-reveal').click();expect(page.locator('#fortune-reveal-result')).to_be_visible()
        ck('cc0' in text('fortune-name') and '年度最常抽到' in text('fortune-name-note'),'fortune_reveal')
        page.screenshot(path=str(out/f'fortune-personal-{width}.png'),full_page=True)
        step(10);ck('個人 占卜：33 次' in text('share-data'),'personal_share_label')
        page.locator('#share-fortune').click();ck('占卜' not in text('share-data'),'fortune_share_optout')
        page.locator('#share-fortune').click();page.locator('#square').click()
        with page.expect_download() as dl:page.locator('#download').click()
        path=out/f'share-square-{width}.png';dl.value.save_as(path);raw=path.read_bytes()
        ck(int.from_bytes(raw[16:20],'big')==1080 and int.from_bytes(raw[20:24],'big')==1080,'square_png')
        page.locator('#portrait').click()
        with page.expect_download() as dl:page.locator('#download').click()
        path=out/f'share-portrait-{width}.png';dl.value.save_as(path);raw=path.read_bytes()
        ck(int.from_bytes(raw[16:20],'big')==1080 and int.from_bytes(raw[20:24],'big')==1440,'portrait_png')
        scenario('fallback')
        ck(all(scope(i)=='PUBLIC' for i in [1,2,3,4,5,7,9]),'new_player_public')
        step(1);ck(text('matches')=='418','public_independent_count')
        ck('非個人成績' in page.locator('#slide-1 .scope-label').inner_text(),'public_battle_label')
        step(9);ck(text('fortune-count')=='264','public_fortune_draws')
        ck(page.locator('#fortune-lifetime').is_hidden() and page.locator('#fortune-streak-box').is_hidden(),'public_no_private_lifetime')
        ck(text('fortune-persona')=='全站命運傾向','public_not_persona')
        page.locator('#fortune-reveal').click();ck('公開樣本' in text('fortune-name-note'),'public_reveal')
        page.screenshot(path=str(out/f'fortune-public-{width}.png'),full_page=True)
        step(10);ck('公開 占卜：264 次' in text('share-data') and '個人 PvP' not in text('share-data'),'public_share_scope')
        scenario('mixed');ck(scope(1)=='PERSONAL' and scope(2)=='PUBLIC' and scope(3)=='PUBLIC' and scope(4)=='PUBLIC' and scope(5)=='PUBLIC' and scope(9)=='PERSONAL','per_chapter_mixed')
        step(10);ck('個人 PvP：174' in text('share-data') and '公開 代表角色' in text('share-data'),'mixed_share_scope')
        page.locator('#skip').click();ck(page.locator('.slide:visible').count()==11,'mixed_summary')
        page.locator('#slide-2 #reveal').click();ck('答案揭曉' in text('guess-feedback'),'summary_context_isolation')
        scenario('fixture');ck(scope(1)=='PERSONAL' and scope(9)=='PUBLIC','small_sample_fortune_fallback')
        step(3);page.locator('#team-best').click();expect(page.locator('#team')).to_have_text('UNKNOWN')
        scenario('conflict');ck(scope(9)=='PUBLIC','duplicate_day_fail_closed');step(9);ck(text('fortune-count')=='264','duplicate_fallback_count')
        scenario('unknown');ck(all(scope(i)=='SKIP' for i in [1,2,3,4,5,7,9]),'both_absent_skip')
        ck(page.locator('#progress button:visible').count()==4,'dynamic_progress')
        page.locator('#start').click();expect(page.locator('#slide-6')).to_be_visible()
        page.locator('#next').click();expect(page.locator('#slide-8')).to_be_visible()
        page.locator('#next').click();expect(page.locator('#slide-10')).to_be_visible()
        ck(text('page-count')=='4 / 4' and '尚無可信統計' in text('share-data'),'no_unknown_share')
        ck(page.locator('#share-fortune').is_hidden(),'no_fortune_share_when_absent')
        page.locator('#skip').click();ck(page.locator('.slide:visible').count()==4,'summary_excludes_skipped')
        ck(page.locator('#slide-9').is_hidden() and page.locator('#slide-1').is_hidden(),'skip_css')
        page.screenshot(path=str(out/f'fallback-empty-{width}.png'),full_page=True)
        ck(not errors,'no_js_errors');ck(not network,'no_external_http')
        reports.append({'viewport':[width,height],'status':'PASS','count':len(cases),'cases':cases});ctx.close()
    b.close()
(out/'qa.json').write_text(json.dumps({'status':'PASS','source':'exact standalone V0.3 HTML loaded into Chromium','reports':reports},ensure_ascii=False,indent=2))
print('FT03CD_CHROMIUM_PASS',[(r['viewport'],r['count']) for r in reports])
