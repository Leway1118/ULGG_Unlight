import sys, pathlib, json, shutil
from playwright.sync_api import sync_playwright,expect
src=pathlib.Path(sys.argv[1]).resolve();out=pathlib.Path(sys.argv[2]);out.mkdir(parents=True,exist_ok=True)
results=[]
with sync_playwright() as p:
    exe=next((shutil.which(x) for x in ['chromium','google-chrome','google-chrome-stable'] if shutil.which(x)),None)
    assert exe,'system Chromium required'
    b=p.chromium.launch(executable_path=exe,headless=True,args=['--no-sandbox','--disable-background-networking'])
    for width,height in [(360,740),(1280,850)]:
        c=b.new_context(viewport={'width':width,'height':height},reduced_motion='reduce',accept_downloads=True,has_touch=width==360,is_mobile=width==360)
        page=c.new_page();cases=[];errors=[];network=[]
        page.on('pageerror',lambda e:errors.append(str(e)))
        page.on('request',lambda r:network.append(r.url) if r.url.startswith(('http:','https:')) else None)
        page.route('http**/*',lambda r:r.abort())
        def ck(v,n):
            assert v,n
            cases.append(n)
        def step(i):
            page.locator('#progress button').nth(i).click()
            expect(page.locator('#slide-'+str(i))).to_be_visible()
            ck(page.evaluate('document.documentElement.scrollWidth<=innerWidth'),'overflow_'+str(i))
        page.set_content(src.read_text(),wait_until='load')
        ck(page.locator('.slide').count()==10,'10_cards')
        ck(page.locator('#unlock-count').inner_text()=='探索 0 / 4','initial_0')
        page.screenshot(path=str(out/f'hero-{width}.png'),full_page=True)
        page.locator('#start').click();expect(page.locator('#matches')).to_have_text('174');ck(page.locator('#rate').inner_text()=='56.3%','win_rate')
        ck(page.evaluate('getComputedStyle(document.querySelector("#slide-1")).animationName')=='none','reduced_motion')
        step(2);ck(page.locator('#reveal-panel').is_hidden(),'hidden')
        page.locator('#guess-options button[data-id="22"]').click();page.locator('#reveal').click()
        expect(page.locator('#guess-feedback')).to_have_text('猜對了！');ck(page.locator('#hero-cards .cardart').count()==3,'reveal')
        step(3);page.locator('#team-best').click();ck('76.4%' in page.locator('#team-matches').inner_text(),'best_team')
        page.locator('#char-best').click();ck('74.6%' in page.locator('#team-matches').inner_text(),'best_char')
        step(4);page.locator('#months button').nth(11).click();expect(page.locator('#month-status')).to_have_text('NOT_APPLICABLE')
        page.locator('#peak-options button[data-month="7"]').click();ck('猜對了' in page.locator('#peak-feedback').inner_text(),'peak_guess')
        step(5);ck(page.locator('#concentration').inner_text()=='43.1%','concentration');ck(page.locator('#hero-rate').inner_text()=='74.7%','hero_rate')
        page.locator('#compare-team').select_option('22-44-55');ck('+20.1' in page.locator('#compare-result').inner_text(),'delta_pp')
        step(6)
        for _ in range(3):page.locator('#quiz button').nth(1).click()
        expect(page.locator('#persona-name')).to_have_text('破陣先鋒')
        step(7);expect(page.locator('#cup-games')).to_have_text('3')
        step(8);ck(page.locator('#unlock-count').inner_text()=='探索 4 / 4','all_unlocked')
        page.locator('#catalog-select').select_option('cc022');ck('薩爾卡多' in page.locator('#catalog-result').inner_text() and 'UNKNOWN' in page.locator('#catalog-result').inner_text(),'catalog_not_mapping')
        ck(page.evaluate("getComputedStyle(document.querySelector('.story-nav')).position==='static'"),'navigation_not_overlay')
        ck(page.evaluate("document.querySelector('.story-nav').getBoundingClientRect().top >= document.querySelector('#slide-8').getBoundingClientRect().bottom-1"),'nav_after_content')
        page.screenshot(path=str(out/f'archive-{width}.png'),full_page=True)
        step(9);page.locator('#share-roles').click();ck('已隱藏' in page.locator('#share-data').inner_text(),'share_privacy')
        page.locator('#square').click()
        with page.expect_download() as dl:page.locator('#download').click()
        dest=out/f'share-square-{width}.png';dl.value.save_as(dest)
        raw=dest.read_bytes();ck(int.from_bytes(raw[16:20],'big')==1080 and int.from_bytes(raw[20:24],'big')==1080,'square_png')
        page.locator('#portrait').click()
        with page.expect_download() as dl:page.locator('#download').click()
        dest=out/f'share-portrait-{width}.png';dl.value.save_as(dest);raw=dest.read_bytes()
        ck(int.from_bytes(raw[16:20],'big')==1080 and int.from_bytes(raw[20:24],'big')==1440,'portrait_png')
        page.locator('#skip').click();ck(page.locator('.slide:visible').count()==10,'summary');page.locator('#skip').click()
        page.locator('#scenario').select_option('fixture');step(3);page.locator('#team-best').click();expect(page.locator('#team')).to_have_text('UNKNOWN')
        step(2);page.locator('#guess-options button').nth(2).click();page.locator('#reveal').click();expect(page.locator('#guess-feedback')).to_have_text('猜對了！')
        step(5);ck(page.locator('#compare-team').is_disabled(),'small_sample_no_comparison')
        page.locator('#scenario').select_option('unknown');step(1);expect(page.locator('#matches')).to_have_text('UNKNOWN');step(2);ck(page.locator('#reveal').is_disabled(),'unknown_no_guess')
        step(4);ck(page.locator('#peak-options button').count()==0,'unknown_no_peak');step(5);ck(page.locator('#concentration').inner_text()=='UNKNOWN','unknown_no_ratio')
        step(8);ck(page.locator('#unlock-count').inner_text()=='探索 0 / 4','reset_state');ck(not errors,'no_js_error');ck(not network,'zero_http')
        results.append({'viewport':[width,height],'cases':cases,'count':len(cases),'status':'PASS'});c.close()
    b.close()
(out/'qa.json').write_text(json.dumps({'status':'PASS','method':'system Chromium, exact standalone HTML, set_content, external HTTP blocked','results':results},ensure_ascii=False,indent=2))
print('FT03A_CHROMIUM_PASS',[(r['viewport'],r['count']) for r in results])
